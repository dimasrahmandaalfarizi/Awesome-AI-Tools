import https from 'node:https';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const README_URL = 'https://raw.githubusercontent.com/public-apis/public-apis/master/README.md';
const OUTPUT_PATH = path.join(__dirname, '..', 'src', 'data', 'apis.ts');

function fetchReadme(url) {
  return new Promise((resolve, reject) => {
    https.get(url, (res) => {
      if (res.statusCode !== 200) {
        reject(new Error(`Failed to fetch: HTTP ${res.statusCode}`));
        return;
      }
      let data = '';
      res.on('data', (chunk) => (data += chunk));
      res.on('end', () => resolve(data));
    }).on('error', reject);
  });
}

function slugify(text) {
  return text
    .toLowerCase()
    .trim()
    .replace(/[^\w\s-]/g, '')
    .replace(/[\s_-]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function parseMarkdownApis(markdown) {
  const lines = markdown.split('\n');
  const apis = [];
  let currentCategory = '';
  const seenIds = new Set();

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();

    if (line.startsWith('### ')) {
      currentCategory = line.replace('### ', '').trim();
      continue;
    }

    // Ignore headers, APILayer promotional suite or empty lines
    if (!currentCategory || currentCategory.includes('APILayer') || !line.startsWith('|')) {
      continue;
    }

    if (line.includes('---') || line.toLowerCase().includes('| api | description')) {
      continue;
    }

    // Example row: | [AdoptAPet](https://www.adoptapet.com/public/apis/pet_list.html) | Resource to help get pets adopted | `apiKey` | Yes | Yes |
    const parts = line.split('|').map((p) => p.trim()).filter((p, index, arr) => index > 0 && index < arr.length - 1);
    if (parts.length < 5) continue;

    const [apiCol, descCol, authCol, httpsCol, corsCol] = parts;

    // Parse API Name & URL
    let name = apiCol;
    let link = '';
    const linkMatch = apiCol.match(/\[([^\]]+)\]\(([^)]+)\)/);
    if (linkMatch) {
      name = linkMatch[1].trim();
      link = linkMatch[2].trim();
    } else {
      name = apiCol.replace(/[`*]/g, '').trim();
    }

    if (!name || !link || !link.startsWith('http')) {
      continue;
    }

    const description = descCol.replace(/\|/g, '-').trim();
    const auth = authCol.replace(/[`]/g, '').trim() || 'No';
    const https = httpsCol.toLowerCase().includes('yes');
    let cors = 'unknown';
    if (corsCol.toLowerCase().includes('yes')) cors = 'yes';
    else if (corsCol.toLowerCase().includes('no')) cors = 'no';

    let baseSlug = slugify(name);
    let id = `api-${baseSlug}`;
    let counter = 1;
    while (seenIds.has(id)) {
      id = `api-${baseSlug}-${counter}`;
      counter++;
    }
    seenIds.add(id);

    apis.push({
      id,
      name,
      slug: baseSlug,
      description,
      auth,
      https,
      cors,
      link,
      category: currentCategory,
    });
  }

  return apis;
}

async function run() {
  console.log('Fetching public-apis repository README.md...');
  const markdown = await fetchReadme(README_URL);
  console.log(`Fetched ${markdown.length} bytes.`);

  const apis = parseMarkdownApis(markdown);
  console.log(`Parsed ${apis.length} public APIs across categories.`);

  // Compute categories breakdown
  const categoryMap = {};
  for (const api of apis) {
    categoryMap[api.category] = (categoryMap[api.category] || 0) + 1;
  }

  const categories = Object.keys(categoryMap).sort().map((cat) => ({
    name: cat,
    slug: slugify(cat),
    count: categoryMap[cat],
  }));

  const fileContent = `// Auto-generated by scripts/sync-public-apis.mjs
// Source: https://github.com/public-apis/public-apis
import { PublicApi } from "@/types"

export interface PublicApiCategory {
  name: string
  slug: string
  count: number
}

export const PUBLIC_API_CATEGORIES: PublicApiCategory[] = ${JSON.stringify(categories, null, 2)}

export const PUBLIC_APIS: PublicApi[] = ${JSON.stringify(apis, null, 2)}
`;

  fs.writeFileSync(OUTPUT_PATH, fileContent, 'utf8');
  console.log(`Successfully generated ${OUTPUT_PATH} with ${apis.length} APIs and ${categories.length} categories.`);
}

run().catch((err) => {
  console.error('Error syncing public APIs:', err);
  process.exit(1);
});
